// SkySeal OS (Pyodide) demo e2e: tower + client tabs share one Python server.
import { chromium } from 'playwright-core';
const BASE = process.argv[2] || 'http://localhost:4600/showcase/skyseal-agent/';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const errors = [];
const watch = (p, name) => { p.on('pageerror', e => errors.push(name + ': ' + e.message)); p.on('console', m => { if (m.type() === 'error' && !/404/.test(m.text())) errors.push(name + ' console: ' + m.text()); }); };
const out = {};
const tower = await ctx.newPage(); watch(tower, 'tower');
let t0 = Date.now();
await tower.goto(BASE + 'tower');
await tower.waitForSelector('.skyseal-demo-overlay', { state: 'detached', timeout: 120000 });
out.towerBootMs = Date.now() - t0;
await tower.click('text=Войти в диспетчерскую');
await tower.waitForSelector('text=Журнал', { timeout: 20000 }).catch(() => {});
await tower.waitForTimeout(1000);
out.towerAfterLogin = (await tower.locator('body').innerText()).slice(0, 200);

const client = await ctx.newPage(); watch(client, 'client');
t0 = Date.now();
await client.goto(BASE);
await client.waitForSelector('.skyseal-demo-overlay', { state: 'detached', timeout: 60000 });
out.clientBootMs = Date.now() - t0;
const fill = async (name, value) => { const el = client.locator(`[name="${name}"]`); if (await el.evaluate(e => e.tagName) === 'SELECT') await el.selectOption({ index: 1 }).catch(() => {}); else await el.fill(value); };
await fill('origin_city', 'Москва'); await fill('origin_address', 'Склад, ул. Лесная 5');
await fill('destination_city', 'Душанбе'); await fill('destination_address', 'Аэропорт DYU');
await fill('cargo_name', 'Запчасти для насосов'); await fill('pieces', '2'); await fill('description', 'Сухой груз, без ограничений');
await fill('weight_kg', '120'); await fill('length_cm', '80'); await fill('width_cm', '60'); await fill('height_cm', '50');
await fill('declared_value', '150000');
await fill('client_name', 'Партнёр Демо'); await fill('client_phone', '+79990000000');
await client.click('text=Подставить демонстрационные фото');
await client.waitForSelector('text=Демо-фото приложены');
const consent = client.locator('.consent input[type="checkbox"]');
if (await consent.count()) await consent.check();
t0 = Date.now();
await client.click('#submitButton');
await client.waitForSelector('.tracking-card', { timeout: 30000 });
out.createMs = Date.now() - t0;
await client.waitForTimeout(3000);
out.clientStatus = (await client.locator('.tracking-card .status').first().innerText().catch(() => '')).trim();

// Tower got it live
out.towerToastNew = await tower.locator('.toast').allInnerTexts();
out.towerConn = await tower.locator('#connectionText').innerText().catch(() => '');
await tower.waitForSelector('.decision-row', { timeout: 20000 });
out.towerRows = await tower.locator('.decision-row').count();
await tower.locator('.decision-row').first().click();
await tower.waitForSelector('.agent-run', { timeout: 20000 });
out.agentRuns = await tower.locator('.agent-run').count();
await tower.waitForFunction(() => [...document.querySelectorAll('.photo-strip img')].every(i => i.complete && i.naturalWidth > 0), null, { timeout: 15000 }).catch(() => {});
out.photos = await tower.locator('.photo-strip img').evaluateAll(els => els.map(e => e.naturalWidth));
await tower.screenshot({ path: 'agent-tower.png' });
await client.screenshot({ path: 'agent-client.png', fullPage: false });
out.hasQuoteButton = await tower.locator('#openQuote').count();
await tower.click('#openQuote');
await tower.click('[data-demo-fill]');
await tower.click('text=Отправить варианты клиенту');
await tower.waitForTimeout(1500);
out.towerToasts = await tower.locator('.toast').allInnerTexts();
out.towerStatusQuote = (await tower.locator('.detail-header .status').first().innerText().catch(() => '')).trim();
out.submitButtons = await tower.locator('#quoteForm button').allInnerTexts();
await tower.screenshot({ path: 'agent-quote.png' });
console.log(JSON.stringify(out, null, 2));
// Client sees the options live and picks the recommended one
await client.waitForSelector('[data-accept-option]', { timeout: 20000 });
out.clientOptions = await client.locator('[data-accept-option]').count();
await tower.evaluate(() => { const orig = EventTarget.prototype.dispatchEvent; window.__ws = []; EventTarget.prototype.dispatchEvent = function (e) { if (e.type === 'message' && String(this.url || '').includes('/ws/')) window.__ws.push(String(e.data).slice(0, 80)); return orig.call(this, e); }; });
await client.locator('[data-accept-option].primary').first().click();
await client.waitForTimeout(1500);
out.clientStatusAfter = (await client.locator('.tracking-card .status').first().innerText().catch(() => '')).trim();
await tower.waitForFunction(() => document.querySelector('.detail-header .status')?.textContent.includes('подтвержд'), null, { timeout: 10000 }).catch(() => {});
out.towerWsAfterAccept = await tower.evaluate(() => window.__ws);
out.apiStatus = await tower.evaluate(async () => { const id = document.querySelector('.detail-header .eyebrow')?.textContent; const list = await (await fetch(new URL('api/operator/shipments', document.baseURI.replace(/tower$/, ''))).catch(() => null))?.json?.(); return list && list.map(x => x.status); });
out.towerStatusAfter = (await tower.locator('.detail-header .status').first().innerText().catch(() => '')).trim();
console.log(JSON.stringify({ ...out, errors }, null, 2));
await browser.close();
