// Aero Cargo static demo: login → passport with demo files → operator approve
// → capacity request → carrier confirmation → passport document.
import { chromium } from 'playwright-core';
const BASE = process.argv[2] || 'http://localhost:4600/showcase/aero-cargo/';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 900 } });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(BASE);
await page.click('#login-button');
await page.waitForSelector('#app-view:not([hidden])', { timeout: 10000 });
await page.click('[data-view="shipments"]');
await page.fill('[name="origin"]', 'Душанбе (DYU)');
await page.fill('[name="destination"]', 'Дубай (DWC)');
await page.fill('[name="content_description"]', 'Запчасти для насосов');
await page.fill('[name="package_type"]', 'Картонные коробки');
await page.fill('[name="pieces"]', '2');
await page.fill('[name="actual_weight_kg"]', '48');
await page.fill('[name="length_cm"]', '60');
await page.fill('[name="width_cm"]', '40');
await page.fill('[name="height_cm"]', '40');
await page.click('text=Подставить демо-файлы');
await page.waitForSelector('text=Демо-файлы приложены', { timeout: 5000 });
await page.check('[name="declaration_accepted"]');
await page.click('#shipment-submit');
await page.waitForSelector('text=SHP-00001', { timeout: 10000 });
await page.click('[data-view="operations"]');
await page.click('#queue-list [data-queue="SHP-00001"]');
await page.click('[data-review="APPROVED_FOR_CAPACITY"]');
await page.waitForSelector('#prepare-capacity', { timeout: 5000 });
await page.fill('#carrier-name', 'Somon Air Cargo');
await page.fill('#departure', '2026-11-02 08:40');
await page.click('#prepare-capacity');
await page.waitForSelector('#carrier-reference', { timeout: 5000 });
await page.fill('#quoted-price', '1850');
await page.fill('#carrier-reference', 'SZ-BKG-77421');
await page.click('[data-capacity="CONFIRMED"]');
await page.waitForTimeout(500);
const panel = await page.locator('#decision-panel').innerText();
const [doc] = await Promise.all([page.waitForEvent('popup'), page.click('text=Паспорт ↗')]);
await doc.waitForLoadState();
const docTitle = await doc.locator('h1').textContent();
await page.click('[data-view="dashboard"]');
await page.waitForTimeout(300);
const metrics = await page.locator('#metric-grid').innerText();
await page.reload();
const afterReload = { url: page.url(), loginVisible: await page.locator('#login-view').isVisible() };
await page.screenshot({ path: 'aero.png' });
console.log(JSON.stringify({ panel: panel.slice(0, 400), docTitle, metrics, afterReload, errors }, null, 2));
await browser.close();
